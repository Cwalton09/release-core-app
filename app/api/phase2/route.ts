export async function POST(
  req: NextRequest
) {
  try {
    const { messages } =
      await req.json();

    if (
      !messages ||
      !Array.isArray(messages) ||
      messages.length === 0
    ) {
      return NextResponse.json(
        {
          error: "No messages provided",
        },
        {
          status: 400,
        }
      );
    }

    const response = await fetch(
      "https://api.anthropic.com/v1/messages",
      {
        method: "POST",

        headers: {
          "Content-Type":
            "application/json",

          "x-api-key":
            process.env
              .ANTHROPIC_API_KEY!,

          "anthropic-version":
            "2023-06-01",
        },

        body: JSON.stringify({
          model:
            "claude-sonnet-4-6",

          max_tokens: 7000,

          system: SYSTEM_PROMPT,

          messages,
        }),
      }
    );

    const data =
      await response.json();

    if (!response.ok) {
      console.error(
        "Anthropic API error:",
        data
      );

      return NextResponse.json(
        {
          error:
            data?.error?.message ||
            "AI request failed",
        },
        {
          status: response.status,
        }
      );
    }

    const text =
      data.content
        ?.map((content: any) =>
          content.type === "text"
            ? content.text
            : ""
        )
        .join("") || "";

    if (!text) {
      return NextResponse.json(
        {
          error:
            "No response returned",
        },
        {
          status: 500,
        }
      );
    }

    return NextResponse.json({
      message: text,
    });
  } catch (error) {
    console.error(
      "Phase 2 session error:",
      error
    );

    return NextResponse.json(
      {
        error:
          "Something went wrong",
      },
      {
        status: 500,
      }
    );
  }
}